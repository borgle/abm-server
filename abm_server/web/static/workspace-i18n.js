let language = "zh";

export function initWorkspacePage({ titleKey = "" } = {}) {
  initPageLanguage({
    translations,
    legacyStorageKeys: ["abm.landing.lang"],
    onApply(nextLanguage) {
      language = nextLanguage;
      if (titleKey) document.title = t(titleKey);
      window.dispatchEvent(new CustomEvent("workspace:language", { detail: nextLanguage }));
    },
  });
}

export function t(key, values) {
  let value = translations[language]?.[key];
  if (typeof value !== "string") return key;
  if (values) {
    for (const [name, replacement] of Object.entries(values)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

export function currentLanguage() {
  return language;
}
